
/*POO - Programação Orientada a Objeto
        Objeto é uma coleção de chave e valor

        Nome: 'Gustavo'
          ^       ^     
        chave   Valor
*/

let aluno = {
    nome: 'Gustavo',
    idade: 18,
    altura: 1.70,
    peso: '60kg'
}

console.log(aluno)

//Pegar o valor de uma determinada propriedade do objeto

console.log(aluno.nome)
console.log(aluno.idade)
console.log(aluno.altura)
console.log(aluno.peso)

